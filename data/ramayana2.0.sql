-- Myth-Verse: manually curated character relationships

CREATE TABLE IF NOT EXISTS character_relationships (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id integer NOT NULL,
    related_character_id integer NOT NULL,
    relationship_type text NOT NULL,

    CONSTRAINT character_relationships_character_fk
        FOREIGN KEY (character_id)
        REFERENCES characters(id)
        ON DELETE CASCADE,

    CONSTRAINT character_relationships_related_fk
        FOREIGN KEY (related_character_id)
        REFERENCES characters(id)
        ON DELETE CASCADE,

    CONSTRAINT character_relationships_not_self
        CHECK (character_id <> related_character_id),

    CONSTRAINT character_relationships_unique
        UNIQUE (character_id, related_character_id, relationship_type)
);

CREATE INDEX IF NOT EXISTS idx_character_relationships_character
    ON character_relationships(character_id);

CREATE INDEX IF NOT EXISTS idx_character_relationships_related
    ON character_relationships(related_character_id);

